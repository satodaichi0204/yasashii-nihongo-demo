/** 言い換えの組（長い言葉から先に置き換える） */
export function paraphrasePairs(): [string, string][] {
  const pairs: [string, string][] = [...WORDS];
  for (const [noun, dict, te, masu, nai] of SURU_VERBS) {
    const ta = te.replace(/て$/, "た").replace(/で$/, "だ");
    pairs.push(
      [`${noun}しないで`, `${nai}で`],
      [`${noun}しない`, nai],
      [`${noun}して`, te],
      [`${noun}した`, ta],
      [`${noun}しま`, `${masu}ま`],
      [`${noun}する`, dict],
    );
  }
  return pairs.sort((a, b) => b[0].length - a[0].length);
}

export const PARAPHRASE_COUNT = SURU_VERBS.length + WORDS.length;
